# install.ps1 -- bootstrap for dsh-comfyui-console
#
# Pure ASCII on purpose: Windows PowerShell 5.1 decodes a BOM-less .ps1 as GBK,
# so any non-ASCII literal in this file would break on some machines.
#
# Usage:
#   powershell -ExecutionPolicy Bypass -File install.ps1
#   powershell -ExecutionPolicy Bypass -File install.ps1 -ComfyRoot "E:\ComfyUI\ComfyUI_windows_portable"
#   powershell -ExecutionPolicy Bypass -File install.ps1 -ComfyRoot "D:\ComfyUI" -PythonExe "D:\py\python.exe" -Force

param(
  [string]$ComfyRoot = '',
  [string]$PythonExe = '',
  [string]$CardsDir  = '',
  [string]$WorkDir   = '',
  [string]$OutputDir = '',
  [int]$ComfyPort = 8188,
  [int]$SidecarPort = 8199,
  [switch]$AllowLan,
  [switch]$Force
)

$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
function Say($m) { Write-Host ('[install] ' + $m) }
function Fail($m) { Write-Host ('[FATAL] ' + $m); exit 1 }

# ---- 1. locate ComfyUI ----
function Test-Comfy([string]$p) {
  if (-not $p) { return $false }
  if (Test-Path -LiteralPath (Join-Path $p 'main.py')) { return $true }
  if (Test-Path -LiteralPath (Join-Path $p 'python_embeded\python.exe')) { return $true }
  return $false
}
if (-not (Test-Comfy $ComfyRoot)) {
  $cands = @()
  if ($env:COMFYUI_ROOT) { $cands += $env:COMFYUI_ROOT }
  $cands += @(
    'E:\ComfyUI\ComfyUI_windows_portable',
    'D:\ComfyUI\ComfyUI_windows_portable',
    'C:\ComfyUI\ComfyUI_windows_portable',
    'F:\ComfyUI\ComfyUI_windows_portable',
    (Join-Path $env:USERPROFILE 'ComfyUI_windows_portable'),
    (Join-Path $env:USERPROFILE 'Desktop\ComfyUI_windows_portable'),
    (Join-Path $env:USERPROFILE 'Downloads\ComfyUI_windows_portable')
  )
  foreach ($c in $cands) { if (Test-Comfy $c) { $ComfyRoot = $c; break } }
}
if (-not (Test-Comfy $ComfyRoot)) {
  Fail 'ComfyUI not found. Pass -ComfyRoot "<dir containing main.py or python_embeded>"'
}
$ComfyRoot = (Resolve-Path -LiteralPath $ComfyRoot).Path
Say ('ComfyUI: ' + $ComfyRoot)

# ---- 2. locate python ----
if (-not $PythonExe) {
  $try = @(
    (Join-Path $ComfyRoot 'python_embeded\python.exe'),
    'D:\paint\venv312\Scripts\python.exe',
    (Join-Path $env:LOCALAPPDATA 'Programs\Python\Python312\python.exe'),
    (Join-Path $env:LOCALAPPDATA 'Programs\Python\Python311\python.exe')
  )
  foreach ($p in $try) { if (Test-Path -LiteralPath $p) { $PythonExe = $p; break } }
}
if (-not $PythonExe -or -not (Test-Path -LiteralPath $PythonExe)) {
  $cmd = Get-Command python.exe -ErrorAction SilentlyContinue
  if ($cmd) { $PythonExe = $cmd.Source }
}
if (-not $PythonExe -or -not (Test-Path -LiteralPath $PythonExe)) {
  Fail 'Python not found. Pass -PythonExe "<python.exe>" (3.10+; standard library only is enough)'
}
Say ('Python: ' + $PythonExe)

# ---- 3. defaults for dirs ----
if (-not $WorkDir)   { $WorkDir = Join-Path $here 'work' }
if (-not $CardsDir)  { $CardsDir = Join-Path $WorkDir 'cards' }
if (-not $OutputDir) { $OutputDir = Join-Path $ComfyRoot 'output' }
foreach ($d in @($WorkDir, $CardsDir)) {
  if (-not (Test-Path -LiteralPath $d)) { New-Item -ItemType Directory -Force -Path $d | Out-Null }
}
Say ('workDir: ' + $WorkDir)
Say ('cardsDir: ' + $CardsDir)

# ---- 4. sanity checks on the package itself ----
foreach ($f in @('expander.py', 'sidecar_auth.py', 'sidecar_cards.py', 'sidecar_comfy.py', 'sidecar_config.py', 'sidecar_llm.py', 'sidecar_pack.py', 'sidecar_routes.py', 'sidecar_state.py', 'sidecar_util.py', 'lib\index.js', 'lib\client.js', 'cordis.patch.yml')) {
  $p = Join-Path $here $f
  if (-not (Test-Path -LiteralPath $p)) { Fail ('package file missing: ' + $p) }
}
& $PythonExe -c "import py_compile,sys; py_compile.compile(sys.argv[1], doraise=True)" (Join-Path $here 'expander.py')
if ($LASTEXITCODE -ne 0) { Fail 'expander.py does not compile -- package is corrupt' }
Say 'expander.py compiles OK'

# ---- 5. write config.json (UTF-8, no BOM) ----
$cfgPath = Join-Path $here 'config.json'
if ((Test-Path -LiteralPath $cfgPath) -and -not $Force) {
  Say 'config.json already exists -- pass -Force to overwrite'
} else {
  $cfg = [ordered]@{
    _note        = 'Generated by install.ps1. Edit paths here; no restart of Windows needed, but the DSH web process must be restarted.'
    comfyRoot    = $ComfyRoot
    pythonExe    = $PythonExe
    workDir      = $WorkDir
    credsFile    = ''
    comfyPort    = $ComfyPort
    sidecarPort  = $SidecarPort
    extraComfyArgs = @('--disable-pinned-memory', '--disable-async-offload', '--disable-dynamic-vram', '--cache-none')
    outputDir    = $OutputDir
    saveDir      = ''
    cardsDir     = $CardsDir
    allowLan     = [bool]$AllowLan
  }
  $json = $cfg | ConvertTo-Json -Depth 5
  [IO.File]::WriteAllText($cfgPath, $json, (New-Object System.Text.UTF8Encoding($false)))
  Say ('config.json written: ' + $cfgPath)
}

# ---- 6. next steps ----
Write-Host ''
Say 'done. Next:'
Write-Host '  1) register the plugin in your DSH profile (copy this folder into %USERPROFILE%\.dsh\plugins\ and add'
Write-Host '     an insert line pointing at it, or use: dsh plugin add <this folder>)'
Write-Host '  2) restart the DSH web process (plugin code is cached per process)'
Write-Host '  3) open the drawing console, then check the sidecar:'
Write-Host ('     Invoke-RestMethod http://127.0.0.1:' + $SidecarPort + '/health')
Write-Host '  4) ComfyUI itself is started from the page (POST /comfy/start) or by your own launcher'
Write-Host ''
Write-Host 'Models are NOT in this package: base model (anima-aesthetic-v1.1 / anima-base-v1.0) +'
Write-Host 'qwen_3_06b_base.safetensors + qwen_image_vae.safetensors must exist under ComfyUI\models\.'
Write-Host 'Character/style LoRAs and LLLite patches arrive as a .dslcard card pack, not as code.'
